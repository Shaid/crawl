#!/usr/bin/env python3
"""Generate vectors.json: ground-truth cases produced by running the game's own
68k routines (oracle binary). Usage: make_vectors.py <s1.bin> <s2.bin>
Deterministic (fixed PRNG seed)."""
import json, random, struct, subprocess, sys, pathlib, hashlib

here = pathlib.Path(__file__).resolve().parent
s1p, s2p = sys.argv[1], sys.argv[2]
ORACLE = str(here / 'oracle')
s2 = open(s2p, 'rb').read()

def run(mode, lines):
    out = subprocess.run([ORACLE, s1p, s2p, mode], input='\n'.join(lines) + '\n',
                         capture_output=True, text=True, check=True).stdout
    return [l for l in out.split('\n') if l]

rnd = random.Random(0xB1AC)
def seed():
    return ''.join('%02x' % rnd.randrange(256) for _ in range(6))

vec = {'note': 'Generated by tools/blackcrypt/rules_oracle/make_vectors.py from the game\'s own code; see docs/blackcrypt/amiga/game-rules.md'}
# tables (S_2 words; A4 = S_2 + 0x7FFE)
def words(off, n): return list(struct.unpack('>%dh' % n, s2[off:off + 2 * n]))
vec['tables'] = {'statBonusT1': words(0x2E4, 31), 'defenseT2': words(0x322, 31), 'speedT3': words(0x360, 31)}

# RNG
cases = []
for _ in range(12):
    s = seed()
    for kind, n in ((0, 0), (8, 20), (8, 100), (16, 9), (16, 100), (16, 0)):
        cases.append((s, kind, n, 24))
res = run('rng', ['%s %d %d %d' % c for c in cases])
vec['rng'] = []
for c, r in zip(cases, res):
    vals = [int(x) for x in r.split(':')[1].split()]
    vec['rng'].append({'seed': c[0], 'kind': c[1], 'n': c[2], 'out': vals})

# level-up
lv = []
for _ in range(240):
    level = rnd.randrange(1, 14); con = rnd.randrange(0, 31)
    xp = rnd.randrange(0, 1 << (level + 11)); hp = rnd.randrange(1, 80)
    lv.append((seed(), xp, level, con, hp))
res = run('levelup', ['%s %x %d %d %d' % c for c in lv])
vec['levelup'] = []
for c, r in zip(lv, res):
    nl, h, m = [int(x) for x in r.split(':')[1].split()]
    vec['levelup'].append({'seed': c[0], 'xp': c[1], 'level': c[2], 'con': c[3], 'hp': c[4], 'newLevel': nl, 'hpAfter': h, 'maxHpAfter': m})

# weapon: full 256x256 matrix (monster type byte x weapon gfx byte), class 0 level 5 extra 7 item 5
inp = ['0 5 %d 7 5 0x%x' % (g, 0x8000 | m) for m in range(256) for g in range(256)]
res = run('weapon', inp)
rows = {}
for l in res:
    h, r = l.split(':'); f = h.split()
    rows[(int(f[6], 16) & 0xff, int(f[3]))] = tuple(int(x) for x in r.split())
base = {g: rows[(0xB3, g)] for g in range(256)}
vec['weaponBase'] = {str(g): list(v[:2]) for g, v in base.items() if v[0] != -4370}
vec['weaponSpecial'] = {}
for m in range(256):
    d = {str(g): list(rows[(m, g)]) for g in range(256) if rows[(m, g)] != base[g]}
    if d: vec['weaponSpecial'][str(m)] = d
vec['weaponMatrixSha1'] = hashlib.sha1(json.dumps(sorted((k, v) for k, v in rows.items())).encode()).hexdigest()
# weapon class/level dependence of case 0 (bare hand)
bh = []
res = run('weapon', ['%d %d 0 0 0 0x80b3' % (c, lv_) for c in range(4) for lv_ in (1, 2, 5, 9)])
for l in res:
    h, r = l.split(':'); f = h.split(); a, b, e = [int(x) for x in r.split()]
    bh.append({'cls': int(f[1]), 'level': int(f[2]), 'base': a, 'sides': b})
vec['bareHand'] = bh

# melee
ml = []
for _ in range(500):
    lvl = rnd.randrange(1, 15); st = rnd.randrange(0, 31); b6c = rnd.randrange(-3, 6)
    hit = rnd.randrange(0, 256); hp = rnd.randrange(30, 400); cls = rnd.randrange(4)
    gfx = rnd.choice([0, 1, 2, 3, 6, 7, 33, 71, 89, 135, 137, 140, 141, 164, 187]); extra = rnd.randrange(0, 12)
    item = 0 if gfx == 0 else 5
    ml.append((seed(), lvl, st, b6c & 0xff if b6c < 0 else b6c, hit, hp, cls, gfx, extra, item))
res = run('melee', ['%s %d %d %d %d %d %d %d %d %d' % c for c in ml])
vec['melee'] = []
for c, r in zip(ml, res):
    after = int(r.split(':')[1])
    b6 = c[3] - 256 if c[3] > 127 else c[3]
    vec['melee'].append({'seed': c[0], 'level': c[1], 'str': c[2], 'b6c': b6, 'monHit': c[4], 'monHp': c[5], 'cls': c[6], 'gfx': c[7], 'extra': c[8], 'item': c[9], 'monHpAfter': after})

# ---- monster-vs-party melee (real 9D28, melee-only monsters)
def sb(v): return v & 0xff
mm = []
for _ in range(2500):
    gfx = rnd.choice([0x80B3, 0x80B3, 0x80B7, 0x80B8, 0x80B9, 0x80C0])
    b2 = rnd.randrange(256); b3 = (rnd.randrange(256) & ~0x2C) | (rnd.choice([2, 3, 3, 1, 0]) << 2)
    b6 = rnd.choice([2, 2, 3, 10, 0])
    maxhp = rnd.randrange(1, 400)
    px, py = rnd.randrange(8, 13), rnd.randrange(8, 13)
    if rnd.random() < 0.8:
        dx, dy = rnd.choice([(0, 1), (0, -1), (1, 0), (-1, 0)])
    else:
        dx, dy = rnd.randrange(-5, 3), rnd.randrange(-5, 3)
    form = list(range(4)); rnd.shuffle(form)
    hps = [rnd.choice([-3, 0, 5, 30, 60]) for _ in range(4)]
    acs = [sb(rnd.randrange(-6, 30)) for _ in range(4)]
    mm.append((seed(), gfx, b2, b3, b6, maxhp, px, py, px - dx, py - dy, rnd.randrange(4), rnd.randrange(5),
               rnd.choice([2, 3, 4, 4]), 1, *form, *hps, *acs, rnd.randrange(2)))
res = run('mmelee', [' '.join(str(x) for x in c) for c in mm])
vec['mmelee'] = []
for c, r in zip(mm, res):
    f = r.split(':')[1].split()
    ret, outflag, s0f, s0a, nd = (int(x) for x in f[:5])
    dm = [[int(f[5 + 2 * k]), int(f[6 + 2 * k])] for k in range(nd)]
    ns = int(f[5 + 2 * nd]); seed_after = f[6 + 2 * nd]
    vec['mmelee'].append({'in': list(c), 'ret': ret, 'outflag': outflag, 's0f': s0f, 's0a': s0a, 'dmg': dm, 'sched': ns, 'seedAfter': seed_after})

# ---- monster death XP (real 7ED0)
xl = []
for _ in range(400):
    xl.append((seed(), rnd.randrange(256), rnd.randrange(0, 2000), rnd.randrange(0, 400),
               *[rnd.choice([-4, 0, 7, 25]) for _ in range(4)], *[rnd.randrange(0, 100000) for _ in range(4)]))
res = run('xp', [' '.join(str(x) for x in c) for c in xl])
vec['xp'] = []
for c, r in zip(xl, res):
    f = r.split(':')[1].split()
    vec['xp'].append({'in': list(c), 'xp': [int(x) for x in f[:4]], 'seedAfter': f[4]})

# ---- behaviour VM (real AAFC); scripts from S_2, pointer table fixed by +0x80
FIRST, TABLE = 0xE92, 0x114A
starts = [(struct.unpack('>I', s2[TABLE + 4 * i:TABLE + 4 * i + 4])[0] - 0xA8BF0 + 0x80 - FIRST) // 6 for i in range(12)]
lens = {}
uniq = sorted(set(starts))
for i, st in enumerate(uniq):
    lens[st] = (uniq[i + 1] if i + 1 < len(uniq) else (TABLE - FIRST) // 6) - st
al = []
for _ in range(1500):
    t = rnd.randrange(12)
    pc = rnd.randrange(1, lens[starts[t]])
    sp = rnd.randrange(1, 13); mhp = rnd.randrange(1, 300); hp = rnd.randrange(-5, mhp + 1)
    b3 = rnd.randrange(256); w0c = rnd.choice([0, 1, 2, 3, 0x8000, 0x4001, 0x2002]); b7 = rnd.randrange(0, 30)
    gfx = rnd.choice([0x80B3, 0x80B7, 0x80B8, 0x80B9])
    px, py = rnd.randrange(8, 13), rnd.randrange(8, 13)
    x, y = px + rnd.randrange(-3, 4), py + rnd.randrange(-3, 4)
    rc = rnd.choice([0, 1, 2])
    vars_ = [rnd.choice([0, 1, 2, 3, 5, 8, 20, 254]) for _ in range(8)]
    al.append((seed(), t, pc, sp, hp, mhp, b3, w0c, b7, gfx, px, py, x, rc, y, *vars_, rnd.randrange(0, 12), rnd.randrange(0, 6), 0))
# oracle arg order: type pc sp hp mhp b3 w0c b7 gfx px py x rc y vars(8) s11 s12 f1E8E
lines = []
for c in al:
    lines.append(' '.join(str(v) for v in c))
out = subprocess.run([ORACLE, s1p, s2p, 'ai'], input='\n'.join(lines) + '\n', capture_output=True, text=True).stdout.split('\n')
vec['ai'] = []
i = 0
for c in al:
    l1, l2 = out[i], out[i + 1]; i += 2
    f = l1.split(':')[1].split()
    steps = int(f[f.index('steps') + 1])
    if steps > 100000:  # runaway script position (no delay op reached)
        continue
    pc, php, smax, gfx, b7, t_, s0e, s11, s12 = (int(x) for x in f[:9])
    vs = [int(x) for x in f[10:18]]
    sc0, sc4 = int(f[19]), int(f[20])
    ents = [e for e in l2.split(' | ') if e.startswith('|') or True]
    log = []
    for e in l2.split('|')[1:]:
        e = e.strip()
        if e.startswith('seed'): seed_after = e.split()[1]; continue
        parts = e.split(',')
        off = int(parts[0], 16); w = [int(x) for x in parts[1:9]]
        log.append({'off': off, 'w': w})
    vec['ai'].append({'in': list(c), 'pc': pc, 'pHp': php, 'sMax': smax, 'gfx': gfx, 'b7': b7, 'type': t_, 's0e': s0e, 's11': s11, 's12': s12, 'vars': vs, 'sc0': sc0, 'sc4': sc4, 'log': log, 'seedAfter': seed_after})
vec['aiScripts'] = {'cells': [[s2[o], s2[o + 1], (s2[o + 2] << 8) | s2[o + 3], (s2[o + 4] << 8) | s2[o + 5]] for o in range(FIRST, TABLE, 6)], 'starts': starts}

# ---- tick handler vitals (real 8B2; due-event list empty)
tl = []
interesting = [0x40, 0x80, 0x100, 0x140, 0x1c0, 0x200, 0x10, 0x20, 0x25, 0x28, 0x08, 0x0d, 0x15, 0x30, 0x50, 0x5, 0x1f0, 0x140 + 0x200, 0x180 + 0x400]
for _ in range(1500):
    t = rnd.choice(interesting) + rnd.choice([0, 0, 0x400, 0x800, 0x1000]) if rnd.random() < 0.7 else rnd.randrange(1, 5000)
    resting = rnd.random() < 0.4
    chars = []
    for _c in range(4):
        mx = rnd.randrange(10, 90)
        chars.append((rnd.choice([-2, 0, 1, rnd.randrange(1, mx + 1), mx]), mx, rnd.randrange(1, 12),
                      rnd.choice([0, 500, 1999, 2000, 3000, 5000]), rnd.choice([0, 700, 1999, 2000, 5000]),
                      rnd.choice([0, 0, 1, 3, 9]), rnd.choice([0, 0, 1, 4]), rnd.choice([0, 1]), rnd.choice([0, 0, 1]), rnd.choice([1, 1, 2, 3])))
    tl.append((seed(), t, int(resting), rnd.choice([0, 0, 1]), 0, rnd.choice([0, 3]), rnd.choice([0, 2]), chars))
lines = []
for c in tl:
    lines.append(' '.join(str(x) for x in c[:7]) + ' ' + ' '.join(' '.join(str(x) for x in ch) for ch in c[7]))
res = run('tick', lines)
vec['tick'] = []
for c, r in zip(tl, res):
    head, tail = r.split(' : ')
    f = tail.split(' | ')
    nums = [int(x) for x in f[0].split()]
    hps, light, hold = nums[:4], nums[4], nums[5]
    calls = []
    for e in f[1:]:
        o, a, b, cc, d = e.split()
        calls.append([o, int(a), int(b), int(cc), int(d)])
    vec['tick'].append({'in': {'seed': c[0], 't': c[1], 'resting': c[2], 'hazard': c[3], 'light': c[5], 'hold': c[6], 'chars': [list(ch) for ch in c[7]]}, 'hp': hps, 'light': light, 'hold': hold, 'calls': calls})

# ---- monster special attacks (real 98A8; disease / poison bits)
sp = []
for _ in range(1500):
    form = list(range(4)); rnd.shuffle(form)
    sp.append((seed(), rnd.choice([14, 15]), rnd.randrange(4), rnd.randrange(5), rnd.randrange(4), rnd.randrange(10, 300), *form,
               *[rnd.choice([-2, 0, 20]) for _ in range(4)], *[rnd.choice([0, 0, 10, 50, 100]) for _ in range(4)], *[rnd.choice([0, 0, 1]) for _ in range(4)],
               *[rnd.choice([0, 0, 0, 1]) for _ in range(4)], *[rnd.randrange(0, 31) for _ in range(4)]))
res = run('spec', [' '.join(str(x) for x in c) for c in sp])
vec['special'] = []
for c, r in zip(sp, res):
    t = r.split(' : ')[1].split()
    nd = int(t[0]); dm = [[int(t[1 + 3 * k]), int(t[2 + 3 * k]), int(t[3 + 3 * k])] for k in range(nd)]
    rest = t[1 + 3 * nd:]
    vec['special'].append({'in': list(c), 'dmg': dm, 'poison': [int(x) for x in rest[1:5]], 'disease': [int(x) for x in rest[6:10]], 'sched': int(rest[11]), 'seedAfter': rest[12]})

json.dump(vec, open(here / 'vectors.json', 'w'), separators=(',', ':'))
print('wrote vectors.json', {k: (len(v) if hasattr(v, '__len__') else v) for k, v in vec.items()})
