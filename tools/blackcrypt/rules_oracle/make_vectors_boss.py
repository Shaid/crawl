#!/usr/bin/env python3
"""Generate vectors_boss.json.gz: the Ram-boss stage-machine item effects PROTECTOR (S_1 +0x78DA), SOULFREEZER (+0x79C2), VORTEX (+0x7B2E)
run in the real 68k (oracle_spell 'script' mode, hooks on the UI / scheduler calls). Usage: make_vectors_boss.py <s1.bin> <s2.bin> [out.json.gz].
FORCEHAMMER (+0x7C40) is not harnessed (animation + object removal); see game-rules.md section 11. Evidence: harness."""
import gzip, json, random, subprocess, sys, pathlib
here = pathlib.Path(__file__).resolve().parent
S1, S2 = sys.argv[1], sys.argv[2]
A4 = 0xA8BF0 + 0x7FFE
rnd = random.Random(0xB055)
def poke(k, off, v): return '%s %d %d' % (k, A4 + off, v)
def peek(k, off): return '%s %d' % (k, A4 + off)
OB = lambda u: -0x6E7A + 0x14 * u
CH = lambda k: 0x1758 + 0xA8 * k
CELL = lambda x, y: -0x37CA + (y << 8) + (x << 2)
DX = [(0, 1), (1, 0), (0, -1), (-1, 0)]
HOOKS = 'H 0xB25A 0 H 0x714 0 H 0x5EA 0 H 0x2D46 0 H 0x4AE 0 H 0x46 0 H 0xFE 0'
cases, lines = [], []
for i in range(900):
    fx = rnd.choice(['prot', 'sf', 'vx'])
    off = {'prot': 0x78DA, 'sf': 0x79C2, 'vx': 0x7B2E}[fx]
    stage = rnd.choice([0, 1, 2, 3, 4, 5]) if rnd.random() < 0.5 else {'prot': 1, 'sf': 2, 'vx': 3}[fx]
    px, py, f = rnd.randrange(5, 12), rnd.randrange(5, 12), rnd.randrange(4)
    walls = (1 << f) if rnd.random() < 0.2 else 0
    tick = rnd.randrange(0, 100000)
    fxp, fyp = px + DX[f][0], py + DX[f][1]
    mons = []   # (P id, S id, gfx, pos, b0A)
    p = [poke('w', 0x1A1E, stage), poke('w', 0x1740, py), poke('w', 0x1742, px), poke('w', 0x1744, f), poke('l', 0x1750, tick), poke('w', 0x1E60, 0)]
    p.append(poke('l', CELL(px, py), walls << 12))
    nm = rnd.choice([0, 1, 1, 1, 2]); head = 0
    for m in range(nm):
        P, S = 1 + 2 * m, 2 + 2 * m
        gfx = rnd.choice([0x80C5, 0x80C5, 0x80B3, 0x80B2]); pos = rnd.choice([4, 4, 0, 1, 2, 3]); b0a = rnd.choice([0, 1, 5]); al = rnd.randrange(250)
        p += [poke('w', OB(P), gfx), poke('w', OB(P) + 0x10, S), poke('b', OB(S) + 0xA, b0a), poke('w', OB(P) + 0x12, head), poke('b', OB(S) + 0xB, pos), poke('b', OB(S) + 0x12, al)]
        head = P; mons.append(dict(P=P, S=S, gfx=gfx, pos=pos, b0a=b0a, alert=al))
    p.append(poke('l', CELL(fxp, fyp), head))
    chars = []
    for k in range(4):
        c = dict(hp=rnd.choice([0, 7, 30]), res=rnd.choice([0, 10, 60, 74, 75, 76, 100, 200]))
        chars.append(c); p += [poke('w', CH(k) + 0x4E, c['hp']), poke('b', CH(k) + 0x69, c['res'])]
    pk = [peek('r16', 0x1A1E)] + [peek('r8', OB(m['S']) + 0x12) for m in mons] + [peek('r8', OB(m['S']) + 0xA) for m in mons] + [peek('r8', CH(k) + 0x69) for k in range(4)]
    lines.append(' '.join(['S', '000000000001', HOOKS] + p + ['C 0x%X 0' % off] + pk))
    cases.append(dict(fx=fx, stage=stage, px=px, py=py, f=f, walls=walls, tick=tick, mons=mons, chars=chars))
out = subprocess.run([str(here / 'oracle_spell'), S1, S2, 'script'], input='\n'.join(lines) + '\n', capture_output=True, text=True, check=True).stdout
res = [l for l in out.split('\n') if l.startswith('script')]
assert len(res) == len(cases)
for c, r in zip(cases, res):
    a, b, rest, _ = r[len('script :'):].split('|')
    pv = [int(x) for x in a.split()]; n = len(c['mons'])
    log = [[int(v, 16) if i == 0 else int(v) for i, v in enumerate(e.split(','))] for e in b.split()[1:]]
    c['out'] = dict(stage=pv[0], alert=pv[1:1 + n], b0a=pv[1 + n:1 + 2 * n], res=pv[1 + 2 * n:], calls=[[e[0]] + e[1:9] for e in log], d0=int(rest.split()[2]))
gzip.open(sys.argv[3] if len(sys.argv) > 3 else str(here / 'vectors_boss.json.gz'), 'wt', compresslevel=9).write(json.dumps(dict(note='Generated by make_vectors_boss.py from the game\'s own code; see game-rules.md', cases=cases), separators=(',', ':')))
print('wrote', len(cases))
