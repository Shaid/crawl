/**
 * Extracts Black Crypt rule tables from the decompressed bcdft image
 * (build/cache/blackcrypt/bcdft_{decompressed,s2_data}.bin, see
 * tools/bcdft_decompress) and bcdfp's DATA hunk. Output:
 * public/assets/blackcrypt/amiga/data/rules-tables.json
 * Evidence: docs/blackcrypt/amiga/game-rules.md.
 */
import { readFileSync, existsSync } from 'node:fs';

const S1_BASE = 0x80058; // S_1 load address; absolute pointers in S_2 = S1_BASE + S_1 offset

const u16 = (b: Uint8Array, o: number) => (b[o] << 8) | b[o + 1];
const s16 = (b: Uint8Array, o: number) => (u16(b, o) << 16) >> 16;
const u32 = (b: Uint8Array, o: number) => ((b[o] << 24) | (b[o + 1] << 16) | (b[o + 2] << 8) | b[o + 3]) >>> 0;
const cstr = (b: Uint8Array, o: number) => { let e = o; while (b[e]) e++; return Buffer.from(b.subarray(o, e)).toString('latin1'); };

/** Decode the gfxNumber switch of the weapon lookup at S_1 +0x0BDE8 (dispatch chain at +0xBEF8..+0xBF68). */
export function decodeWeaponSwitch(s1: Uint8Array): Record<string, [number, number]> {
  const out: Record<string, [number, number]> = {};
  let a = 0xbef8; let v = 0;
  const handler = (t: number): [number, number] | null =>
    u16(s1, t) === 0x34bc && u16(s1, t + 4) === 0x36bc ? [s16(s1, t + 2), s16(s1, t + 6)] : null;
  // case 0 is `tst.w d0 ; beq.w` -> bare hand (class/level dependent), skipped here
  a += 2 + 4;
  while (a < 0xbf6a) {
    const op = u16(s1, a);
    let imm: number;
    if ((op & 0xf1ff) === 0x5140) imm = ((op >> 9) & 7) || 8;
    else if (op === 0x0440) { imm = u16(s1, a + 2); a += 2; }
    else break;
    a += 2;
    const br = u16(s1, a);
    let tgt: number;
    if ((br & 0xff00) !== 0x6700) break;
    if ((br & 0xff) === 0) { tgt = a + 2 + s16(s1, a + 2); a += 4; } else { tgt = a + 2 + ((br << 24) >> 24); a += 2; }
    v += imm;
    const h = handler(tgt);
    if (h) out[String(v)] = h;
  }
  return out;
}

export function extractRulesTables(s1: Uint8Array, s2: Uint8Array, bcdfp: Uint8Array) {
  const words = (o: number, n: number) => Array.from({ length: n }, (_, i) => s16(s2, o + 2 * i));
  // class templates: bcdfp DATA hunk (file 0x566C + 0x146), 38 B each
  const base = 0x566c + 0x146;
  const classes = [0, 1, 2, 3].map(i => {
    const o = base + i * 38;
    const w = (k: number) => u16(bcdfp, o + 14 + 2 * k);
    return {
      classIndex: i, name: cstr(bcdfp, o),
      // template word order is the creation-screen order; record slots +0x64..+0x68 receive words 0,2,1,4,3
      statsStart: [w(0), w(1), w(2), w(3), w(4)], spareStatPoints: w(5),
      statsMin: [w(6), w(7), w(8), w(9), w(10)], portraitBase: w(11),
    };
  });
  const spells = Array.from({ length: 60 }, (_, i) => {
    const o = 0x12 + 8 * i;
    return { idx: i, name: cstr(s1, u32(s2, o) - S1_BASE), recharge: u16(s2, o + 4), spellLevel: s2[o + 6], nextInPage: s2[o + 7] };
  });
  return {
    note: 'Generated by tools/blackcrypt/rules-tables.ts; see docs/blackcrypt/amiga/game-rules.md',
    statBonusT1: words(0x2e4, 31),
    defenseT2: words(0x322, 31),
    speedT3: words(0x360, 31),
    xp: { rule: 'level L advances while xp > 2^(L+7); threshold doubles per level gained', thresholds: Array.from({ length: 20 }, (_, i) => 2 ** (i + 8)) },
    levelUp: { hpGain: 'rand16(9) + statBonusT1[stat+0x67] + 7 (cur and max)' },
    newCharacter: { level: 1, hp: 20, maxHp: 20, food: 5000, water: 5000, energy: 10000 },
    classes, spells,
    weaponBase: decodeWeaponSwitch(s1),
  };
}

export function buildRulesTables(cacheDir: string, dataDir: string) {
  const f1 = `${cacheDir}/bcdft_decompressed.bin`, f2 = `${cacheDir}/bcdft_s2_data.bin`;
  if (!existsSync(f1) || !existsSync(f2)) return null;
  return extractRulesTables(readFileSync(f1), readFileSync(f2), readFileSync(`${dataDir}/bcdfp`));
}
