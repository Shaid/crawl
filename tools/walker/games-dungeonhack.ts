/**
 * Dungeon Hack (DOS/VGA, SSI/DreamForge 1993) `GameView`.
 *
 * Same shape as the EOB3 walker (`games-eotb3.ts`): the first-person view is the
 * game's own AESOP/16 bytecode (`dungeon`, `features`, `doors`, NPC, items ...
 * classes of HACK.RES) run on `tools/aesop/vm.ts`, composited by
 * `tools/dungeonhack/engine.ts`, whose native routines (wall slots, visibility
 * clipping, step tables, R250 RNG) are ports of AESOP.EXE's own x86 code. The
 * mazes are not stored in the game data: MAZE.EXE generates them from
 * SAVEGAME/SETTINGS.DAT, so the maps here come from running the game's own
 * MAZE.EXE headlessly (scripts/run_dungeonhack_maze.py) for four fixed seeds.
 *
 * Level id = dungeon * 100 + level (dungeon 0 = the shipped SETTINGS.DAT seed
 * 0x000156E0; 1..3 = seeds 1..3 with the shipped settings; 25 levels each).
 *
 * Confidence: maps, features, monsters and items = MAZE.EXE + game bytecode
 * (generated by the game's own code; frames viewed, pixel parity with the real
 * game not checkable here). Per-level wall/floor themes are drawn by the game's
 * `randomize graphics` from our R250 seeded with the maze seed -- the real game
 * seeds it from the clock at start-up, so the THEME choice is a stand-in (art,
 * geometry and placement are the game's). Not wired: monsters moving/attacking,
 * item pick-up, keys/locks, levers, spinners, pits, hint parchments, automap,
 * the HUD. Doors open/close on `use` (F / Space) without a key check.
 */
import type { KeyStateLike, Pose, DrawItem, RGBAColor, PieceBankLookup } from '@seer-project/dungeon';
import type { SlotTableFile } from '@seer-project/dungeon/schema';
import type { GameView } from './games.ts';
import { DhEngine, VIEW_W, VIEW_H, type DhPack } from '../dungeonhack/engine.ts';

const STEP_COOLDOWN_MS = 175;
const TIMER_MS = 70;
export const LEVELS_PER_DUNGEON = 25;

let packPromise: Promise<DhPack> | null = null;

async function fetchJSON<T>(url: string): Promise<T> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status} ${res.statusText}`);
  return res.json() as Promise<T>;
}

export function loadDhPack(assetBase: string): Promise<DhPack> {
  packPromise ??= (async () => {
    const base = `${assetBase}/data/walker`;
    const [classes, palettes, bitmapIndex, natives, dungeons, bin] = await Promise.all([
      fetchJSON<{ classes: DhPack['classes'] }>(`${base}/aesop-classes.json`),
      fetchJSON<DhPack['palettes']>(`${base}/palettes.json`),
      fetchJSON<DhPack['bitmapIndex']>(`${base}/bitmaps-index.json`),
      fetchJSON<DhPack['natives']>(`${base}/natives.json`),
      fetchJSON<{ dungeons: DhPack['dungeons'] }>(`${base}/dungeons.json`),
      fetch(`${base}/bitmaps.bin`).then((r) => r.arrayBuffer()),
    ]);
    return { classes: classes.classes, palettes, bitmapIndex, natives, dungeons: dungeons.dungeons, bitmaps: new Uint8Array(bin) };
  })();
  return packPromise;
}

export function dungeonLabel(pack: DhPack, d: number): string {
  const dg = pack.dungeons[d]!;
  return `${d === 0 ? 'shipped' : 'seed ' + dg.seed.toString(16).toUpperCase().padStart(8, '0')}`;
}

export async function dungeonhackLevelList(assetBase: string): Promise<Array<{ id: number; label: string }>> {
  const pack = await loadDhPack(assetBase);
  const out: Array<{ id: number; label: string }> = [];
  pack.dungeons.forEach((dg, d) => {
    for (let l = 0; l < dg.levels.length; l++) out.push({ id: d * 100 + l, label: `${dungeonLabel(pack, d)} (${dg.seed.toString(16).toUpperCase().padStart(8, '0')}) - level ${l + 1}` });
  });
  return out;
}

const DIRS: Array<[number, number]> = [[0, -1], [1, 0], [0, 1], [-1, 0]];

/** Arrival after climbing up: the open cell beside the previous level's down stairs, facing away from them. */
export function arriveFromBelow(engine: DhEngine): Pose {
  for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x++) {
    if (!engine.cellObjects(x, y, 0).some((id) => engine.classNameOf(id) === 'current stairs down')) continue;
    for (let f = 0; f < 4; f++) {
      const nx = (x + DIRS[f]![0]!) & 31, ny = (y + DIRS[f]![1]!) & 31;
      if (engine.impedance(nx, ny) >= 0) return { level: engine.level, x: nx, y: ny, facing: f as Pose['facing'] };
    }
  }
  const e = engine.entry();
  return { level: engine.level, x: e.x, y: e.y, facing: e.fdir as Pose['facing'] };
}

export class DungeonHackView implements GameView {
  readonly id = 'dungeonhack';
  readonly gameLabel = 'Dungeon Hack';
  readonly items: DrawItem[] = [];
  readonly banks: PieceBankLookup = {};
  readonly slots: SlotTableFile = { schemaVersion: 1, banks: [], slotRows: [] } as unknown as SlotTableFile;
  readonly automap = undefined;
  private pose_: Pose;
  private tick = 0;
  private noclip = false;
  private cooldown = 0;
  private timerClock = 0;
  private anim = 0;
  private img: ImageData | null = null;
  private lastKey = '';
  private pendingLevel: Pose | null = null;
  private message: string | null = null;
  private usePressed = false;

  readonly engine: DhEngine;
  private readonly dungeon: number;
  private readonly label: string;
  constructor(engine: DhEngine, dungeon: number, label: string, start: Pose) {
    this.engine = engine;
    this.dungeon = dungeon;
    this.label = label;
    this.pose_ = start;
  }

  get levelId(): number { return this.pose_.level; }
  get levelLabel(): string { return this.label; }
  get pose(): Pose { return this.pose_; }
  get currentTick(): number { return this.tick; }
  get palette(): RGBAColor[] {
    return Array.from({ length: 256 }, (_, i) => { const [r, g, b] = this.engine.rgb(i); return { r, g, b, a: 255 }; });
  }

  takeLevelChange(): Pose | null { const p = this.pendingLevel; this.pendingLevel = null; return p; }
  takeMessage(): string | null { const m = this.message; this.message = null; return m; }

  /** Try to step; returns the new pose or null when blocked. Level changes are queued for the harness. */
  private move(mtype: 2 | 4 | 5 | 6): Pose | null {
    const { x, y, facing } = this.pose_;
    const t = this.engine.stepTo(x, y, facing, mtype);
    if (!this.noclip) {
      const imp = this.engine.impedance(t.x, t.y);
      const here = this.pose_.level % 100;
      if (imp === -2) {
        const names = this.engine.cellObjects(t.x, t.y, 0).map((id) => this.engine.classNameOf(id));
        if (names.includes('current stairs down') && here + 1 < LEVELS_PER_DUNGEON) {
          this.message = `stairs down -> level ${here + 2}`;
          this.pendingLevel = { level: this.dungeon * 100 + here + 1, x: -1, y: -1, facing: 0 };
        } else if (names.includes('current stairs up') && here > 0) {
          this.message = `stairs up -> level ${here}`;
          this.pendingLevel = { level: this.dungeon * 100 + here - 1, x: -2, y: -2, facing: 0 };
        }
        return null;
      }
      if (imp < 0) return null;
    }
    const here = this.pose_.level % 100;
    let np: Pose = { level: this.pose_.level, x: t.x, y: t.y, facing };
    for (const id of this.engine.cellObjects(t.x, t.y, 0)) {
      const tp = this.engine.teleportOf(id);
      if (!tp) continue;
      this.message = 'teleporter';
      if (tp.level === here) np = { level: this.pose_.level, x: tp.x, y: tp.y, facing: (tp.fdir & 3) as Pose['facing'] };
      else { this.pendingLevel = { level: this.dungeon * 100 + tp.level, x: tp.x, y: tp.y, facing: (tp.fdir & 3) as Pose['facing'] }; return null; }
    }
    return np;
  }

  update(dtMs: number, keys: KeyStateLike): Pose | null {
    this.tick += dtMs;
    this.timerClock += dtMs;
    while (this.timerClock >= TIMER_MS) {
      this.timerClock -= TIMER_MS;
      if (this.engine.tickTimers()) this.anim++;
    }
    const usePressed = keys.isDown('KeyF') || keys.isDown('Space');
    if (usePressed && !this.usePressed) {
      const d = DIRS[this.pose_.facing]!;
      const n = this.engine.useCell((this.pose_.x + d[0]!) & 31, (this.pose_.y + d[1]!) & 31);
      if (n) { this.anim++; this.message = 'use'; }
    }
    this.usePressed = usePressed;
    this.cooldown = Math.max(0, this.cooldown - dtMs);
    if (this.cooldown > 0) return null;
    let { x, y, facing } = this.pose_;
    let changed = false;
    const turn = keys.isDown('KeyQ') || keys.isDown('ArrowLeft') ? -1 : keys.isDown('KeyE') || keys.isDown('ArrowRight') ? 1 : 0;
    if (turn) { facing = ((facing + turn + 4) & 3) as Pose['facing']; changed = true; }
    const mtype = keys.isDown('KeyW') || keys.isDown('ArrowUp') ? 2 : keys.isDown('KeyS') || keys.isDown('ArrowDown') ? 5
      : keys.isDown('KeyA') ? 4 : keys.isDown('KeyD') ? 6 : 0;
    if (!changed && mtype) {
      const np = this.move(mtype as 2 | 4 | 5 | 6);
      if (np) { x = np.x; y = np.y; facing = np.facing; changed = true; }
      else this.cooldown = STEP_COOLDOWN_MS;
    }
    if (!changed) return null;
    this.cooldown = STEP_COOLDOWN_MS;
    this.pose_ = { level: this.pose_.level, x, y, facing };
    return this.pose_;
  }

  setPose(pose: Pose): void { this.pose_ = pose; }
  setNoclip(on: boolean): void { this.noclip = on; }
  interactCodes(): string[] { return []; }
  automapCodes(): string[] { return []; }
  pick(): void { /* no hotspots yet */ }

  /** The composited 176x120 palette-index frame (exposed for tests / frame dumps). */
  frame(): Uint8Array {
    const { x, y, facing } = this.pose_;
    return this.engine.frame(x, y, facing);
  }

  renderCanvas(ctx: CanvasRenderingContext2D): void {
    const key = `${this.pose_.level},${this.pose_.x},${this.pose_.y},${this.pose_.facing},${this.anim}`;
    if (key === this.lastKey && this.img) return;
    this.lastKey = key;
    const ix = this.frame();
    if (!this.img) this.img = ctx.createImageData(VIEW_W, VIEW_H);
    for (let i = 0; i < ix.length; i++) {
      const [r, g, b] = this.engine.rgb(ix[i]!);
      this.img.data[i * 4] = r; this.img.data[i * 4 + 1] = g; this.img.data[i * 4 + 2] = b; this.img.data[i * 4 + 3] = 255;
    }
    ctx.canvas.width = VIEW_W;
    ctx.canvas.height = VIEW_H;
    ctx.putImageData(this.img, 0, 0);
  }

  debugKey(): string { return this.lastKey; }
}

export async function loadDungeonHackView(assetBase: string, levelId: number, startPose: Pose | null): Promise<DungeonHackView> {
  const pack = await loadDhPack(assetBase);
  const d = Math.min(pack.dungeons.length - 1, Math.floor(levelId / 100));
  const l = Math.min(pack.dungeons[d]!.levels.length - 1, levelId % 100);
  const id = d * 100 + l;
  const engine = new DhEngine(pack);
  engine.loadLevel(d, l);
  const label = `${dungeonLabel(pack, d)} level ${l + 1}`;
  let start: Pose;
  if (startPose && startPose.x === -2) start = { ...arriveFromBelow(engine), level: id };
  else if (startPose && startPose.x >= 0) start = { ...startPose, level: id };
  else { const e = engine.entry(); start = { level: id, x: e.x, y: e.y, facing: (e.fdir & 3) as Pose['facing'] }; }
  return new DungeonHackView(engine, d, label, start);
}
