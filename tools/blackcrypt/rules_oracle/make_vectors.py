#!/usr/bin/env python3
"""Generate vectors.json: ground-truth cases produced by running the game's own
68k routines (oracle binary). Usage: make_vectors.py <s1.bin> <s2.bin>
Deterministic (fixed PRNG seed)."""
import json, random, struct, subprocess, sys, pathlib, hashlib

here = pathlib.Path(__file__).resolve().parent
s1p, s2p = sys.argv[1], sys.argv[2]
ORACLE = str(here / 'oracle')
s2 = open(s2p, 'rb').read()

def run(mode, lines):
    out = subprocess.run([ORACLE, s1p, s2p, mode], input='\n'.join(lines) + '\n',
                         capture_output=True, text=True, check=True).stdout
    return [l for l in out.split('\n') if l]

rnd = random.Random(0xB1AC)
def seed():
    return ''.join('%02x' % rnd.randrange(256) for _ in range(6))

vec = {'note': 'Generated by tools/blackcrypt/rules_oracle/make_vectors.py from the game\'s own code; see docs/blackcrypt/amiga/game-rules.md'}
# tables (S_2 words; A4 = S_2 + 0x7FFE)
def words(off, n): return list(struct.unpack('>%dh' % n, s2[off:off + 2 * n]))
vec['tables'] = {'statBonusT1': words(0x2E4, 31), 'defenseT2': words(0x322, 31), 'speedT3': words(0x360, 31)}

# RNG
cases = []
for _ in range(12):
    s = seed()
    for kind, n in ((0, 0), (8, 20), (8, 100), (16, 9), (16, 100), (16, 0)):
        cases.append((s, kind, n, 24))
res = run('rng', ['%s %d %d %d' % c for c in cases])
vec['rng'] = []
for c, r in zip(cases, res):
    vals = [int(x) for x in r.split(':')[1].split()]
    vec['rng'].append({'seed': c[0], 'kind': c[1], 'n': c[2], 'out': vals})

# level-up
lv = []
for _ in range(240):
    level = rnd.randrange(1, 14); con = rnd.randrange(0, 31)
    xp = rnd.randrange(0, 1 << (level + 11)); hp = rnd.randrange(1, 80)
    lv.append((seed(), xp, level, con, hp))
res = run('levelup', ['%s %x %d %d %d' % c for c in lv])
vec['levelup'] = []
for c, r in zip(lv, res):
    nl, h, m = [int(x) for x in r.split(':')[1].split()]
    vec['levelup'].append({'seed': c[0], 'xp': c[1], 'level': c[2], 'con': c[3], 'hp': c[4], 'newLevel': nl, 'hpAfter': h, 'maxHpAfter': m})

# weapon: full 256x256 matrix (monster type byte x weapon gfx byte), class 0 level 5 extra 7 item 5
inp = ['0 5 %d 7 5 0x%x' % (g, 0x8000 | m) for m in range(256) for g in range(256)]
res = run('weapon', inp)
rows = {}
for l in res:
    h, r = l.split(':'); f = h.split()
    rows[(int(f[6], 16) & 0xff, int(f[3]))] = tuple(int(x) for x in r.split())
base = {g: rows[(0xB3, g)] for g in range(256)}
vec['weaponBase'] = {str(g): list(v[:2]) for g, v in base.items() if v[0] != -4370}
vec['weaponSpecial'] = {}
for m in range(256):
    d = {str(g): list(rows[(m, g)]) for g in range(256) if rows[(m, g)] != base[g]}
    if d: vec['weaponSpecial'][str(m)] = d
vec['weaponMatrixSha1'] = hashlib.sha1(json.dumps(sorted((k, v) for k, v in rows.items())).encode()).hexdigest()
# weapon class/level dependence of case 0 (bare hand)
bh = []
res = run('weapon', ['%d %d 0 0 0 0x80b3' % (c, lv_) for c in range(4) for lv_ in (1, 2, 5, 9)])
for l in res:
    h, r = l.split(':'); f = h.split(); a, b, e = [int(x) for x in r.split()]
    bh.append({'cls': int(f[1]), 'level': int(f[2]), 'base': a, 'sides': b})
vec['bareHand'] = bh

# melee
ml = []
for _ in range(500):
    lvl = rnd.randrange(1, 15); st = rnd.randrange(0, 31); b6c = rnd.randrange(-3, 6)
    hit = rnd.randrange(0, 256); hp = rnd.randrange(30, 400); cls = rnd.randrange(4)
    gfx = rnd.choice([0, 1, 2, 3, 6, 7, 33, 71, 89, 135, 137, 140, 141, 164, 187]); extra = rnd.randrange(0, 12)
    item = 0 if gfx == 0 else 5
    ml.append((seed(), lvl, st, b6c & 0xff if b6c < 0 else b6c, hit, hp, cls, gfx, extra, item))
res = run('melee', ['%s %d %d %d %d %d %d %d %d %d' % c for c in ml])
vec['melee'] = []
for c, r in zip(ml, res):
    after = int(r.split(':')[1])
    b6 = c[3] - 256 if c[3] > 127 else c[3]
    vec['melee'].append({'seed': c[0], 'level': c[1], 'str': c[2], 'b6c': b6, 'monHit': c[4], 'monHp': c[5], 'cls': c[6], 'gfx': c[7], 'extra': c[8], 'item': c[9], 'monHpAfter': after})
json.dump(vec, open(here / 'vectors.json', 'w'), separators=(',', ':'))
print('wrote vectors.json', {k: (len(v) if hasattr(v, '__len__') else v) for k, v in vec.items()})
