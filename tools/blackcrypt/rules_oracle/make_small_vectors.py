#!/usr/bin/env python3
"""Derives the small committed fixtures (vectors_move.small.json.gz, vectors_spell.small.json.gz) from the FULL generated sets
(./generated/*.json.gz, produced by gen_vectors.sh): per kind, a few cases of every distinct result *shape* (digits collapsed)
so rare outcomes (door opens, kills, bindings, possession, stone) stay covered, then an even stride up to the budget.
Usage: make_small_vectors.py [full_move.json.gz full_spell.json.gz]"""
import gzip, json, re, sys, pathlib
from collections import defaultdict
here = pathlib.Path(__file__).resolve().parent
mv = sys.argv[1] if len(sys.argv) > 1 else str(here / 'generated/vectors_move.json.gz')
sp = sys.argv[2] if len(sys.argv) > 2 else str(here / 'generated/vectors_spell.json.gz')

def pick(items, shape, per_shape, budget):
    seen = defaultdict(int); out = []; rest = []
    for it in items:
        k = shape(it)
        if seen[k] < per_shape: seen[k] += 1; out.append(it)
        else: rest.append(it)
    if len(out) < budget and rest:
        st = max(1, len(rest) // (budget - len(out)))
        out += rest[::st][:budget - len(out)]
    return out[:max(budget, len(out))]

m = json.load(gzip.open(mv))
by = defaultdict(list)
for c in m['cases']: by[c['k']].append(c)
cases = []
for k, l in by.items(): cases += pick(l, lambda c: tuple(sorted(set(re.findall(r'openDoor|damage|hold|special|sched|ev', c['out'])))) + (tuple(c['out'].split(' ')[1:2]) if c['k'] in ('path', 'enter', 'pursue', 'approach', 'wander', 'act') else ()), 2, 600 if k == 'mover' else 100)
m['cases'] = cases
m['note'] += ' [small committed subset: shape-stratified, about 100 per kind; the full set is generated by gen_vectors.sh]'
gzip.open(here / 'vectors_move.small.json.gz', 'wt', compresslevel=9).write(json.dumps(m, separators=(',', ':')))

s = json.load(gzip.open(sp))
for k, v in list(s.items()):
    if isinstance(v, list) and len(v) > 20 and isinstance(v[0], dict) and 'out' in v[0]:
        s[k] = pick(v, lambda c: (c.get('spell'), c.get('bit'), bool(c['out'].get('b25a')), bool(c['out'].get('sched')), bool(c['out'].get('corpse')), bool(c['out'].get('statue'))), 2, 300 if k == 'facing' else 80)
s['note'] += ' [small committed subset: shape-stratified, about 80 per list; the full set is generated by gen_vectors.sh]'
gzip.open(here / 'vectors_spell.small.json.gz', 'wt', compresslevel=9).write(json.dumps(s, separators=(',', ':')))
print({k: len(v) for k, v in s.items() if isinstance(v, list)}, len(cases))
