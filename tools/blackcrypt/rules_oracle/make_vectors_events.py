#!/usr/bin/env python3
"""Generate vectors_events.json.gz (small enough to commit, 600 cases): the buff-expiry event handlers 0x1E..0x25 of the tick handler (S_1 +0x1F34 dispatch chain, run from +0x12BA to
the common exit +0x1F9C by oracle_spell's `G start stop` / `D n v` tokens). Usage: make_vectors_events.py <s1.bin> <s2.bin> [out.json].
Deterministic. Evidence: harness. See docs/blackcrypt/amiga/game-rules.md section 11."""
import gzip, json, random, subprocess, sys, pathlib
here = pathlib.Path(__file__).resolve().parent
S1, S2 = sys.argv[1], sys.argv[2]
A4 = 0xA8BF0 + 0x7FFE
rnd = random.Random(0xE7E47)
def poke(k, off, v): return '%s %d %d' % (k, A4 + off, v)
def peek(k, off): return '%s %d' % (k, A4 + off)
CH = lambda k: 0x1758 + 0xA8 * k
CBYTES = [0x62, 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x78, 0x79, 0x7A, 0x7B, 0x7C, 0x82, 0x83, 0x84, 0x85]
GW = [0x1E28, 0x1E2A, 0x1E2C, 0x1E2E, 0x1A1E]
GB = [0x1748, 0x174C, 0x174D]
cases, lines = [], []
for i in range(600):
    t = rnd.choice([0x1E, 0x1F, 0x20, 0x21, 0x23, 0x24, 0x25])
    ev = dict(type=t, a1=rnd.randrange(4), a2=rnd.choice([0, 0, 0, 1, 2, 3, 4]) if t in (0x1E, 0x1F) else 0, a3=rnd.choice([1, 2, 3, 5, 75, 200]))
    mode = rnd.choice([0, 1, 3, 4, 10]); a14 = rnd.randrange(4); a16 = rnd.randrange(4); a26 = rnd.choice([0, 0, 1])
    chars = []
    for k in range(4):
        c = dict(hp=rnd.choice([0, -3, 1, 12, 40]), b={o: rnd.choice([0, 0, 1, 2, 3, 74, 75, 76, 100, 200, 255, rnd.randrange(256)]) for o in CBYTES})
        chars.append(c)
    g = {o: rnd.choice([0, 1, 2, 3, 7, 0xFFFF]) for o in GW}
    tick = rnd.randrange(1, 100000)
    p = [poke('w', 0x174A, mode), poke('w', 0x1A14, a14), poke('w', 0x1A16, a16), poke('b', 0x1A26, a26), poke('l', 0x1750, tick), poke('b', 0x173F, 0), poke('b', 0x1036 + 9, 0x96)]
    p += [poke('l', 0x1036, tick), poke('b', 0x1036 + 4, t), poke('b', 0x1036 + 5, ev['a1']), poke('b', 0x1036 + 6, ev['a2']), poke('b', 0x1036 + 7, ev['a3'])]
    for k, c in enumerate(chars):
        p.append(poke('w', CH(k) + 0x4E, c['hp'] & 0xFFFF))
        for o, v in c['b'].items(): p.append(poke('b', CH(k) + o, v))
    for o, v in g.items(): p.append(poke('w', o, v))
    pk = []
    for k in range(4):
        pk.append(peek('r8', CH(k) + 0x4E) if False else peek('r16s', CH(k) + 0x4E))
        for o in CBYTES: pk.append(peek('r8', CH(k) + o))
    for o in GW: pk.append(peek('r16', o))
    for o in GB: pk.append(peek('r8', o))
    lines.append(' '.join(['S', '000000000001'] + p + ['G 0x12BA 0x1F9C', 'D 7 0'] + pk))
    cases.append(dict(ev=ev, mode=mode, a14=a14, a16=a16, a26=a26, chars=chars, g={str(o): v for o, v in g.items()}, tick=tick))
out = subprocess.run([str(here / 'oracle_spell'), S1, S2, 'script'], input='\n'.join(lines) + '\n', capture_output=True, text=True, check=True).stdout
res = [l for l in out.split('\n') if l.startswith('script')]
assert len(res) == len(cases), (len(res), len(cases))
for c, r in zip(cases, res):
    peeks = [int(x) for x in r[len('script :'):].split('|')[0].split()]
    n = len(CBYTES) + 1
    c['out'] = dict(chars=[dict(hp=peeks[k * n], b=dict(zip(map(str, CBYTES), peeks[k * n + 1:(k + 1) * n]))) for k in range(4)],
                    g=dict(zip(map(str, GW), peeks[4 * n:4 * n + len(GW)])), f=dict(zip(map(str, GB), peeks[4 * n + len(GW):])))
vec = dict(note='Generated by make_vectors_events.py from the game\'s own code (S_1 +0x12BA..+0x1F9C); see game-rules.md', cbytes=CBYTES, gw=GW, gb=GB, cases=cases)
gzip.open(sys.argv[3] if len(sys.argv) > 3 else str(here / 'vectors_events.json.gz'), 'wt', compresslevel=9).write(json.dumps(vec, separators=(',', ':')))
print('wrote', len(cases))
